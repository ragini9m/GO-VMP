"""
Shared drawing code for visualize_g.py and visualize_pairwise.py.

Data: the random dummy instance of int main() in views_voxels_motion.cpp
(srand(1), 10 views, 10 voxels, start view 0, Linux/glibc rand()), generated by
test_overlap_formulation.py. Solver: HiGHS via scipy, the same ILP that gave
identical results to Gurobi for the (g) constraint.
"""
import math
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.gridspec import GridSpec
from matplotlib.lines import Line2D
from matplotlib.patches import FancyArrowPatch

import test_overlap_formulation as T

# The Windows console uses cp1252, which cannot print τ
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

# Fixed roles (reference palette, light mode)
SURFACE = "#fcfcfb"
INK = "#0b0b0b"
INK_2 = "#52514e"
MUTED = "#a3a29c"
GRID = "#d9d8d3"
SELECTED = "#2a78d6"   # selected views + registration edges between them
PATH = "#eb6834"       # robot motion path

NUM_VIEW, NUM_VOXEL, START, SEED = 10, 10, 0, 1


def instance():
    m, R = T.generate_instance(NUM_VIEW, NUM_VOXEL, START, SEED)
    return m, R, T.overlap_ratio(R)


def layout(n):
    """Views on a circle, view 0 (start) at the top."""
    return {i: (math.sin(2 * math.pi * i / n), math.cos(2 * math.pi * i / n)) for i in range(n)}


def graph_stats(path, o, tau):
    """Registration graph of the selected views (start excluded): edges, bridges, loops, components."""
    sel = [i for i in path if i != START]
    edges = [(a, b) for x, a in enumerate(sel) for b in sel[x + 1:] if o[a, b] >= tau]
    st = T.reg_stats(sel, (o >= tau).astype(int))

    def ncomp(es):
        parent = {i: i for i in sel}
        def f(a):
            while parent[a] != a:
                a = parent[a]
            return a
        for a, b in es:
            parent[f(a)] = f(b)
        return len({f(i) for i in sel})

    base = ncomp(edges)
    bridges = [e for e in edges if ncomp([x for x in edges if x != e]) > base]
    return dict(edges=edges, bridges=bridges, loops=st["cycle_rank"], comps=base, min_deg=st["min_deg"])


def draw_panel(ax, title, result, o, tau):
    """One configuration: candidate overlaps, selected views, registration edges, motion path."""
    pos = layout(NUM_VIEW)
    ax.set_facecolor(SURFACE)
    ax.set_aspect("equal")
    ax.axis("off")
    ax.set_xlim(-1.35, 1.35)
    ax.set_ylim(-1.45, 1.35)

    # all registrable pairs among the candidate views (context)
    for i in range(1, NUM_VIEW):
        for j in range(i + 1, NUM_VIEW):
            if o[i, j] >= tau:
                ax.plot(*zip(pos[i], pos[j]), color=GRID, lw=1, zorder=1)

    if result is None:
        for i in range(NUM_VIEW):
            ax.scatter(*pos[i], s=380, color=SURFACE, edgecolor=MUTED, lw=1.2, zorder=3)
            ax.text(*pos[i], str(i), ha="center", va="center", fontsize=9, color=MUTED, zorder=4)
        ax.set_title(title, fontsize=10, color=INK, pad=4)
        ax.text(0, -1.38, "infeasible: no selection satisfies the constraint", ha="center", fontsize=8.5, color=INK_2)
        return

    cost, path = result
    gs = graph_stats(path, o, tau)
    selected = set(path)

    # registration edges between selected views; bridges dashed
    for a, b in gs["edges"]:
        bridge = (a, b) in gs["bridges"]
        ax.plot(*zip(pos[a], pos[b]), color=SELECTED, lw=2.6, ls=(0, (4, 3)) if bridge else "-",
                zorder=2, solid_capstyle="round")

    # motion path arrows with step numbers
    for step, (a, b) in enumerate(zip(path[:-1], path[1:]), start=1):
        arr = FancyArrowPatch(pos[a], pos[b], arrowstyle="-|>", mutation_scale=11, lw=1.6, color=PATH,
                              shrinkA=12, shrinkB=12, connectionstyle="arc3,rad=0.18", zorder=5)
        ax.add_patch(arr)

    # views
    for i in range(NUM_VIEW):
        if i == START:
            ax.scatter(*pos[i], s=400, marker="s", color=INK_2, edgecolor=SURFACE, lw=2, zorder=6)
            ax.text(*pos[i], str(i), ha="center", va="center", fontsize=9, color=SURFACE, zorder=7)
        elif i in selected:
            ax.scatter(*pos[i], s=400, color=SELECTED, edgecolor=SURFACE, lw=2, zorder=6)
            ax.text(*pos[i], str(i), ha="center", va="center", fontsize=9, color="white", weight="bold", zorder=7)
        else:
            ax.scatter(*pos[i], s=380, color=SURFACE, edgecolor=MUTED, lw=1.2, zorder=6)
            ax.text(*pos[i], str(i), ha="center", va="center", fontsize=9, color=MUTED, zorder=7)

    ax.set_title(title, fontsize=10, color=INK, pad=4)
    ax.text(0, -1.30, f"cost {cost:.0f}   path {'-'.join(map(str, path))}", ha="center", fontsize=8.5, color=INK)
    ax.text(0, -1.47, f"{len(gs['edges'])} reg. edges · {gs['loops']} loop(s) · {len(gs['bridges'])} bridge(s)"
            + ("" if gs["comps"] <= 1 else f" · {gs['comps']} groups"),
            ha="center", fontsize=8.5, color=INK_2)


def draw_overlap_matrix(ax, o, taus):
    n = o.shape[0]
    shown = np.where(np.eye(n, dtype=bool), np.nan, o)
    im = ax.imshow(shown, cmap="Blues", vmin=0, vmax=1)
    for i in range(n):
        for j in range(n):
            if i != j:
                v = o[i, j]
                ax.text(j, i, f"{v:.2f}".lstrip("0") if v > 0 else "0", ha="center", va="center", fontsize=6.5,
                        color="white" if v > 0.5 else INK)
    ax.set_xticks(range(n))
    ax.set_yticks(range(n))
    ax.tick_params(labelsize=8, colors=INK_2, length=0)
    for s in ax.spines.values():
        s.set_visible(False)
    ax.set_title("Overlap ratio o_ij (Jaccard) between candidate views", fontsize=10, color=INK, loc="left")
    ax.set_xlabel("view j", fontsize=8.5, color=INK_2)
    ax.set_ylabel("view i", fontsize=8.5, color=INK_2)
    cb = plt.colorbar(im, ax=ax, fraction=0.046, pad=0.03)
    cb.ax.tick_params(labelsize=7.5, colors=INK_2)
    cb.outline.set_visible(False)


def draw_cost_bars(ax, labels, costs, baseline_cost):
    y = np.arange(len(labels))[::-1]
    for yi, c in zip(y, costs):
        if c is None:
            ax.text(baseline_cost * 0.02, yi, "infeasible", va="center", fontsize=8.5, color=INK_2)
        else:
            ax.barh(yi, c, height=0.55, color=SELECTED if c != baseline_cost or yi == y[0] else SELECTED)
            ax.text(c + 2, yi, f"{c:.0f}  (+{(c / baseline_cost - 1) * 100:.0f}%)" if yi != y[0] else f"{c:.0f}",
                    va="center", fontsize=8.5, color=INK)
    ax.set_yticks(y)
    ax.set_yticklabels(labels, fontsize=8.5, color=INK)
    ax.tick_params(axis="x", labelsize=8, colors=INK_2)
    ax.tick_params(axis="y", length=0)
    for s in ("top", "right", "left"):
        ax.spines[s].set_visible(False)
    ax.spines["bottom"].set_color(GRID)
    ax.grid(axis="x", color=GRID, lw=0.6)
    ax.set_axisbelow(True)
    ax.set_xlim(0, max(c for c in costs if c is not None) * 1.3)
    ax.set_title("Motion cost of the optimal solution", fontsize=10, color=INK, loc="left")
    ax.set_xlabel("motion cost (sum of m_ij on the path)", fontsize=8.5, color=INK_2)


def legend_handles():
    return [
        Line2D([], [], marker="s", ls="", color=INK_2, markersize=9, label="start view (0)"),
        Line2D([], [], marker="o", ls="", color=SELECTED, markersize=9, label="selected view"),
        Line2D([], [], marker="o", ls="", markerfacecolor=SURFACE, markeredgecolor=MUTED, markersize=9,
               label="not selected"),
        Line2D([], [], color=PATH, lw=1.6, marker=">", markersize=5, label="motion path"),
        Line2D([], [], color=SELECTED, lw=2.6, label="registration edge (o_ij ≥ τ, both selected)"),
        Line2D([], [], color=SELECTED, lw=2.6, ls=(0, (4, 3)), label="bridge (failure splits network)"),
        Line2D([], [], color=GRID, lw=1, label="registrable pair among candidates"),
    ]


def make_figure(title, subtitle, configs, results, o, out_base):
    """configs: list of (panel title, short label, tau or None). results: list of (cost, path) or None."""
    import textwrap
    taus = sorted({c[2] for c in configs if c[2] is not None})
    ncol = len(configs)
    width = max(3.3 * ncol, 13.5)
    fig = plt.figure(figsize=(width, 10.2), facecolor=SURFACE)
    gs = GridSpec(3, ncol, height_ratios=[0.07, 1.0, 0.85], hspace=0.22, wspace=0.05, figure=fig,
                  left=0.04, right=0.98, top=0.90, bottom=0.10)

    fig.text(0.04, 0.975, title, fontsize=14, weight="bold", color=INK, va="top")
    fig.text(0.04, 0.945, subtitle, fontsize=9.5, color=INK_2, va="top")
    fig.legend(handles=legend_handles(), loc="upper left", ncol=4, frameon=False, fontsize=8.5,
               labelcolor=INK, handlelength=2.2, columnspacing=1.6, bbox_to_anchor=(0.035, 0.93))

    for c, (cfg, res) in enumerate(zip(configs, results)):
        ax = fig.add_subplot(gs[1, c])
        draw_panel(ax, cfg[0], res, o, cfg[2] if cfg[2] is not None else min(taus))

    # bottom row: heatmap | gap for the bar labels | bars
    bottom = gs[2, :].subgridspec(1, 3, width_ratios=[1.0, 0.22, 1.35], wspace=0.0)
    draw_overlap_matrix(fig.add_subplot(bottom[0]), o, taus)
    costs = [r[0] if r else None for r in results]
    draw_cost_bars(fig.add_subplot(bottom[2]), [c[1] for c in configs], costs, costs[0])

    note = ("Dummy data of int main() in views_voxels_motion.cpp: srand(1), 10 views, 10 voxels, start view 0, "
            "Linux rand(). View 0 is the start view and sees no voxels. Views are placed on a circle for "
            "readability; positions have no geometric meaning. Thresholds used: τ = "
            + ", ".join(str(t) for t in taus) + "; the baseline panel shows registrable pairs at τ = "
            + str(min(taus)) + ".")
    fig.text(0.04, 0.035, "\n".join(textwrap.wrap(note, int(width * 15))), fontsize=7.5, color=INK_2, va="bottom")
    for ext in ("png", "pdf"):
        fig.savefig(f"{out_base}.{ext}", dpi=200, facecolor=SURFACE)
    plt.close(fig)
    print(f"written {out_base}.png and {out_base}.pdf")
